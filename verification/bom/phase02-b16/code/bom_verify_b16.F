C !ROUTINE: BOM_VERIFY_B16
C !INTERFACE:
      SUBROUTINE BOM_VERIFY_B16( myThid )

C !DESCRIPTION:
C     Compare production JULIA component and fixed-step RK paths with the
C     checksummed B16 golden files generated by Julia 1.10.12.

      IMPLICIT NONE
#include "SIZE.h"
#include "EEPARAMS.h"
#include "PARAMS.h"
#include "BOM_SIZE.h"
#include "BOM.h"
      INTEGER myThid
      _RL coeff(4,2,BOM_ENV_NSOURCE)
      _RL particleX(3), particleY(3)
      _RL c0Value, cxValue, cyValue, ctValue
      INTEGER*8 particleId(3)
      INTEGER ioUnit, ioStatus, iRow, sourceCode, componentCode
      INTEGER nFail, globalFail, rhsFail, rk2Fail, rk4Fail
      CHARACTER*512 header
      CHARACTER*(MAX_LEN_MBUF) msgBuf
CEOP

      nFail = 0
      rhsFail = 0
      rk2Fail = 0
      rk4Fail = 0
      coeff = 0. _d 0
      ioUnit = 71
      OPEN(UNIT=ioUnit,FILE='input_fields_v1.csv',STATUS='OLD',
     &     ACTION='READ',IOSTAT=ioStatus)
      CALL BOM_B16_ASSERT(ioStatus.EQ.0,nFail)
      IF ( ioStatus.EQ.0 ) THEN
        READ(ioUnit,'(A)',IOSTAT=ioStatus) header
        DO iRow=1,6
          READ(ioUnit,*,IOSTAT=ioStatus)
     &         sourceCode, componentCode,
     &         c0Value,cxValue,cyValue,ctValue
          CALL BOM_B16_ASSERT(ioStatus.EQ.0,nFail)
          IF ( ioStatus.EQ.0 .AND.
     &         sourceCode.GE.1 .AND.
     &         sourceCode.LE.BOM_ENV_NSOURCE .AND.
     &         componentCode.GE.1 .AND.
     &         componentCode.LE.2 ) THEN
            coeff(1,componentCode,sourceCode) = c0Value
            coeff(2,componentCode,sourceCode) = cxValue
            coeff(3,componentCode,sourceCode) = cyValue
            coeff(4,componentCode,sourceCode) = ctValue
          ELSE
            nFail = nFail+1
          ENDIF
        ENDDO
        CLOSE(ioUnit)
      ENDIF

      ioUnit = 72
      OPEN(UNIT=ioUnit,FILE='input_particles_v1.csv',STATUS='OLD',
     &     ACTION='READ',IOSTAT=ioStatus)
      CALL BOM_B16_ASSERT(ioStatus.EQ.0,nFail)
      IF ( ioStatus.EQ.0 ) THEN
        READ(ioUnit,'(A)',IOSTAT=ioStatus) header
        DO iRow=1,3
          READ(ioUnit,*,IOSTAT=ioStatus)
     &         particleId(iRow),particleX(iRow),particleY(iRow)
          CALL BOM_B16_ASSERT(ioStatus.EQ.0,nFail)
        ENDDO
        CLOSE(ioUnit)
      ENDIF

      _BEGIN_MASTER(myThid)
      bomEquationMode = 'JULIA'
      bomCurrentPolicy = 'EULERIAN'
      bomStokesSource = 'FILES'
      bomWindSource = 'EXF'
      bomAlpha = 0.00337 _d 0
      bomTauDays = 0.0103 _d 0
      bomTau = bomTauDays*86400. _d 0
      bomR = 0.823 _d 0
      bomSigma = 1.2 _d 0
      bomAdvCFL = 0.9 _d 0
      deltaTClock = 900. _d 0
      _END_MASTER(myThid)
      _BARRIER
      CALL BOM_B16_ASSERT(bomTau.EQ.889.92 _d 0,nFail)

      CALL BOM_B16_VERIFY_RHS(coeff,rhsFail,myThid)
      CALL BOM_B16_VERIFY_TRAJECTORY(
     I     'golden_traj_julia_rk2_v1.csv','RK2',
     I     coeff,particleId,particleX,particleY,
     U     rk2Fail,myThid )
      CALL BOM_B16_VERIFY_TRAJECTORY(
     I     'golden_traj_julia_rk4_v1.csv','RK4',
     I     coeff,particleId,particleX,particleY,
     U     rk4Fail,myThid )
      nFail = nFail+rhsFail+rk2Fail+rk4Fail
      globalFail = nFail
      CALL GLOBAL_SUM_INT(globalFail,myThid)
      _BEGIN_MASTER(myThid)
      IF ( myProcId.EQ.0 ) THEN
        IF ( rhsFail.EQ.0 ) THEN
          WRITE(msgBuf,'(A)')
     &         'P2-I05 PASS: locked B16 inputs and JULIA RHS'
          CALL PRINT_MESSAGE(msgBuf,standardMessageUnit,
     &                       SQUEEZE_RIGHT,myThid)
        ENDIF
        IF ( rk2Fail+rk4Fail.EQ.0 ) THEN
          WRITE(msgBuf,'(A)')
     &         'P2-I06 PASS: B16 fixed RK2/RK4 trajectories'
          CALL PRINT_MESSAGE(msgBuf,standardMessageUnit,
     &                       SQUEEZE_RIGHT,myThid)
        ENDIF
      ENDIF
      _END_MASTER(myThid)
      IF ( globalFail.GT.0 ) THEN
        CALL ALL_PROC_DIE(0)
        STOP 'ABNORMAL END: P2.4 B16 GATE'
      ENDIF
      RETURN
      END

C---+----1----+----2----+----3----+----4----+----5----+----6----+----7-|--+----|
      SUBROUTINE BOM_B16_VERIFY_RHS(coeff,nFail,myThid)

      IMPLICIT NONE
#include "SIZE.h"
#include "EEPARAMS.h"
#include "BOM_SIZE.h"
#include "BOM.h"
      _RL coeff(4,2,BOM_ENV_NSOURCE)
      INTEGER nFail,myThid
      _RL refDiag(BOM_RHS_NDIAG),rhsDiag(BOM_RHS_NDIAG)
      _RL paperDiag(BOM_RHS_NDIAG)
      _RL timeRef,xRef,yRef,rhsXRef,rhsYRef,rhsX,rhsY
      _RL ix,jy,wetWeight,stageCFL,tolerance,maxModeDiff
      _RL time0,time1
      INTEGER ioUnit,ioStatus,iRow,iDiag,bi,bj,iter0
      INTEGER failCode,failStage,nOwner,nChecked
      INTEGER*8 idRef
      LOGICAL isLocal,isWet,isOwner,rhsValid,didModeCheck
      CHARACTER*512 header

      ioUnit = 73
      nChecked = 0
      didModeCheck = .FALSE.
      OPEN(UNIT=ioUnit,FILE='golden_rhs_julia_v1.csv',STATUS='OLD',
     &     ACTION='READ',IOSTAT=ioStatus)
      CALL BOM_B16_ASSERT(ioStatus.EQ.0,nFail)
      IF ( ioStatus.NE.0 ) RETURN
      READ(ioUnit,'(A)',IOSTAT=ioStatus) header
      DO iRow=1,9
        READ(ioUnit,*,IOSTAT=ioStatus)
     &       idRef,timeRef,xRef,yRef,rhsXRef,rhsYRef,
     &       (refDiag(iDiag),iDiag=1,BOM_RHS_NDIAG)
        CALL BOM_B16_ASSERT(ioStatus.EQ.0,nFail)
        IF ( ioStatus.NE.0 ) CYCLE
        IF ( timeRef.LT.86400. _d 0 ) THEN
          time0 = timeRef
          time1 = timeRef+900. _d 0
          iter0 = NINT(timeRef/900. _d 0)
        ELSE
          time0 = 85500. _d 0
          time1 = 86400. _d 0
          iter0 = 95
        ENDIF
        CALL BOM_B16_PUBLISH(
     I       coeff,time0,time1,iter0,myThid)
        nOwner = 0
        DO bj=myByLo(myThid),myByHi(myThid)
         DO bi=myBxLo(myThid),myBxHi(myThid)
          CALL BOM_LOCATE_INITIAL(
     I         xRef,yRef,bi,bj,
     O         ix,jy,isLocal,isWet,myThid)
          IF ( isLocal ) THEN
            nOwner = nOwner+1
            CALL BOM_RHS_SLOW_MANIFOLD(
     I           xRef,yRef,timeRef,900. _d 0,
     I           bi,bj,BOM_STAGE_K1,
     O           rhsX,rhsY,ix,jy,rhsDiag,
     O           wetWeight,stageCFL,
     O           isOwner,rhsValid,failCode,failStage,myThid)
            CALL BOM_B16_ASSERT(rhsValid .AND. isOwner,nFail)
            tolerance = 2. _d -12+5. _d -12*ABS(rhsXRef)
            CALL BOM_B16_ASSERT(ABS(rhsX-rhsXRef).LE.tolerance,
     U                          nFail)
            tolerance = 2. _d -12+5. _d -12*ABS(rhsYRef)
            CALL BOM_B16_ASSERT(ABS(rhsY-rhsYRef).LE.tolerance,
     U                          nFail)
            DO iDiag=1,BOM_RHS_NDIAG
              tolerance = 2. _d -12
     &                  +5. _d -12*ABS(refDiag(iDiag))
              CALL BOM_B16_ASSERT(
     I             ABS(rhsDiag(iDiag)-refDiag(iDiag)).LE.tolerance,
     U             nFail)
            ENDDO
            nChecked = nChecked+1

C--         The fixture must distinguish compatibility and paper modes.
            IF ( .NOT.didModeCheck ) THEN
              bomEquationMode = 'PAPER2024'
              CALL BOM_RHS_SLOW_MANIFOLD(
     I             xRef,yRef,timeRef,900. _d 0,
     I             bi,bj,BOM_STAGE_K1,
     O             rhsX,rhsY,ix,jy,paperDiag,
     O             wetWeight,stageCFL,
     O             isOwner,rhsValid,failCode,failStage,myThid)
              bomEquationMode = 'JULIA'
              maxModeDiff = 0. _d 0
              DO iDiag=1,BOM_RHS_NDIAG
                maxModeDiff = MAX(maxModeDiff,
     &               ABS(paperDiag(iDiag)-rhsDiag(iDiag)))
              ENDDO
              CALL BOM_B16_ASSERT(rhsValid .AND.
     &             maxModeDiff.GT.1. _d -8,nFail)
              didModeCheck = .TRUE.
            ENDIF
          ENDIF
         ENDDO
        ENDDO
        CALL BOM_B16_ASSERT(nOwner.EQ.1,nFail)
      ENDDO
      CLOSE(ioUnit)
      CALL BOM_B16_ASSERT(nChecked.EQ.9,nFail)
      CALL BOM_B16_ASSERT(didModeCheck,nFail)
      RETURN
      END

C---+----1----+----2----+----3----+----4----+----5----+----6----+----7-|--+----|
      SUBROUTINE BOM_B16_VERIFY_TRAJECTORY(
     I                 fileName,integrator,coeff,
     I                 particleId,particleX,particleY,
     U                 nFail,myThid)

      IMPLICIT NONE
#include "SIZE.h"
#include "EEPARAMS.h"
#include "BOM_SIZE.h"
#include "BOM.h"
      CHARACTER*(*) fileName,integrator
      _RL coeff(4,2,BOM_ENV_NSOURCE)
      INTEGER*8 particleId(3)
      _RL particleX(3),particleY(3)
      INTEGER nFail,myThid
      _RL xState(3),yState(3),pathState(3)
      _RL xCandidate,yCandidate,rhsDiag(BOM_RHS_NDIAG)
      _RL ix,jy,wetWeight,stageCFL,time0,time1
      _RL refTime,refX,refY,refPath,tolerance,stepLength
      INTEGER*8 refId
      INTEGER ioUnit,ioStatus,iPart,iStep,iDiag,bi,bj
      INTEGER ownerBi,ownerBj,nOwner,failCode,failStage,nRows
      LOGICAL isLocal,isWet,stepValid
      CHARACTER*512 header

      ioUnit = 74
      IF ( integrator.EQ.'RK4' ) ioUnit = 75
      OPEN(UNIT=ioUnit,FILE=fileName,STATUS='OLD',
     &     ACTION='READ',IOSTAT=ioStatus)
      CALL BOM_B16_ASSERT(ioStatus.EQ.0,nFail)
      IF ( ioStatus.NE.0 ) RETURN
      READ(ioUnit,'(A)',IOSTAT=ioStatus) header
      nRows = 0
      DO iPart=1,3
        xState(iPart) = particleX(iPart)
        yState(iPart) = particleY(iPart)
        pathState(iPart) = 0. _d 0
        READ(ioUnit,*,IOSTAT=ioStatus)
     &       refId,refTime,refX,refY,refPath
        CALL BOM_B16_ASSERT(ioStatus.EQ.0 .AND.
     &       refId.EQ.particleId(iPart) .AND.
     &       refTime.EQ.0. _d 0 .AND.
     &       refX.EQ.xState(iPart) .AND.
     &       refY.EQ.yState(iPart) .AND.
     &       refPath.EQ.0. _d 0,nFail)
        nRows = nRows+1
      ENDDO

      DO iStep=1,96
        time0 = DFLOAT(iStep-1)*900. _d 0
        time1 = DFLOAT(iStep)*900. _d 0
        CALL BOM_B16_PUBLISH(coeff,time0,time1,iStep-1,myThid)
        DO iPart=1,3
          nOwner = 0
          ownerBi = 0
          ownerBj = 0
          DO bj=myByLo(myThid),myByHi(myThid)
           DO bi=myBxLo(myThid),myBxHi(myThid)
            CALL BOM_LOCATE_INITIAL(
     I           xState(iPart),yState(iPart),bi,bj,
     O           ix,jy,isLocal,isWet,myThid)
            IF ( isLocal ) THEN
              nOwner = nOwner+1
              ownerBi = bi
              ownerBj = bj
            ENDIF
           ENDDO
          ENDDO
          CALL BOM_B16_ASSERT(nOwner.EQ.1,nFail)
          IF ( integrator.EQ.'RK2' ) THEN
            CALL BOM_RK2_SLOW_MIGRATE(
     I           xState(iPart),yState(iPart),time0,900. _d 0,
     I           ownerBi,ownerBj,
     O           xCandidate,yCandidate,ix,jy,rhsDiag,
     O           wetWeight,stageCFL,
     O           failStage,failCode,stepValid,myThid)
          ELSE
            CALL BOM_RK4_SLOW_MIGRATE(
     I           xState(iPart),yState(iPart),time0,900. _d 0,
     I           ownerBi,ownerBj,
     O           xCandidate,yCandidate,ix,jy,rhsDiag,
     O           wetWeight,stageCFL,
     O           failStage,failCode,stepValid,myThid)
          ENDIF
          CALL BOM_B16_ASSERT(stepValid,nFail)
          stepLength = SQRT((xCandidate-xState(iPart))**2
     &                     +(yCandidate-yState(iPart))**2)
          pathState(iPart) = pathState(iPart)+stepLength
          xState(iPart) = xCandidate
          yState(iPart) = yCandidate
          READ(ioUnit,*,IOSTAT=ioStatus)
     &         refId,refTime,refX,refY,refPath
          CALL BOM_B16_ASSERT(ioStatus.EQ.0 .AND.
     &         refId.EQ.particleId(iPart) .AND.
     &         refTime.EQ.time1,nFail)
          tolerance = MAX(1. _d -6,5. _d -11*refPath)
          CALL BOM_B16_ASSERT(
     I         ABS(xState(iPart)-refX).LE.tolerance .AND.
     &         ABS(yState(iPart)-refY).LE.tolerance,nFail)
          CALL BOM_B16_ASSERT(
     I         ABS(pathState(iPart)-refPath).LE.tolerance,nFail)
          nRows = nRows+1
        ENDDO
      ENDDO
      READ(ioUnit,*,IOSTAT=ioStatus) refId
      CALL BOM_B16_ASSERT(ioStatus.LT.0,nFail)
      CLOSE(ioUnit)
      CALL BOM_B16_ASSERT(nRows.EQ.291,nFail)
      DO iDiag=1,BOM_RHS_NDIAG
        CALL BOM_B16_ASSERT(rhsDiag(iDiag).EQ.rhsDiag(iDiag),nFail)
      ENDDO
      RETURN
      END

C---+----1----+----2----+----3----+----4----+----5----+----6----+----7-|--+----|
      SUBROUTINE BOM_B16_PUBLISH(
     I                 coeff,time0,time1,iter0,myThid)

      IMPLICIT NONE
#include "SIZE.h"
#include "EEPARAMS.h"
#include "GRID.h"
#include "BOM_SIZE.h"
#include "BOM.h"
      _RL coeff(4,2,BOM_ENV_NSOURCE),time0,time1
      INTEGER iter0,myThid
      INTEGER bi,bj,i,j,iSource,iEnd
      _RL xValue,yValue,pointTime,fValue
      LOGICAL wetPoint

      fValue = 2.18213 _d 0/86400. _d 0
      DO bj=myByLo(myThid),myByHi(myThid)
       DO bi=myBxLo(myThid),myBxHi(myThid)
        DO j=1-OLy,sNy+OLy
         DO i=1-OLx,sNx+OLx
          xValue = xC(i,j,bi,bj)
          yValue = yC(i,j,bi,bj)
          wetPoint = maskC(i,j,1,bi,bj).GT.0.
          bomTauSphere(i,j,bi,bj) = 0. _d 0
          bomFCori(i,j,bi,bj) = fValue
          bomMetricValid(i,j,bi,bj) = wetPoint
          DO iSource=1,BOM_ENV_NSOURCE
           DO iEnd=1,BOM_ENV_NEND
            IF ( iEnd.EQ.BOM_ENV_OLD ) THEN
              pointTime = time0
            ELSE
              pointTime = time1
            ENDIF
            bomEnvEast(i,j,iEnd,iSource,bi,bj) =
     &           coeff(1,1,iSource)+coeff(2,1,iSource)*xValue
     &          +coeff(3,1,iSource)*yValue
     &          +coeff(4,1,iSource)*pointTime
            bomEnvNorth(i,j,iEnd,iSource,bi,bj) =
     &           coeff(1,2,iSource)+coeff(2,2,iSource)*xValue
     &          +coeff(3,2,iSource)*yValue
     &          +coeff(4,2,iSource)*pointTime
            bomEnvValid(i,j,iEnd,iSource,bi,bj) = wetPoint
            bomGradEastEast(i,j,iEnd,iSource,bi,bj) =
     &           coeff(2,1,iSource)
            bomGradNorthEast(i,j,iEnd,iSource,bi,bj) =
     &           coeff(3,1,iSource)
            bomGradEastNorth(i,j,iEnd,iSource,bi,bj) =
     &           coeff(2,2,iSource)
            bomGradNorthNorth(i,j,iEnd,iSource,bi,bj) =
     &           coeff(3,2,iSource)
            bomGradValid(i,j,iEnd,iSource,bi,bj) = wetPoint
           ENDDO
          ENDDO
         ENDDO
        ENDDO
       ENDDO
      ENDDO
      _BEGIN_MASTER(myThid)
      bomEnvTime(BOM_ENV_OLD) = time0
      bomEnvTime(BOM_ENV_NEW) = time1
      bomEnvIter(BOM_ENV_OLD) = iter0
      bomEnvIter(BOM_ENV_NEW) = iter0+1
      bomEnvReady = .TRUE.
      bomGradReady = .TRUE.
      bomMetricReady = .TRUE.
      _END_MASTER(myThid)
      _BARRIER
      RETURN
      END

C---+----1----+----2----+----3----+----4----+----5----+----6----+----7-|--+----|
      SUBROUTINE BOM_B16_ASSERT(condition,nFail)
      IMPLICIT NONE
      LOGICAL condition
      INTEGER nFail
      IF ( .NOT.condition ) nFail = nFail+1
      RETURN
      END
